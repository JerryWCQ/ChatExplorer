const DICTS: Record<Lang, Record<MessageKey, string>> = { en, "zh-CN": zhCN };

export type Vars = Record<string, string | number>;

/** A bound translator. Components receive one of these and never see raw keys. */
export type T = (key: MessageKey, vars?: Vars) => string;

export function translator(lang: Lang): T {
  const dict = DICTS[lang];
  return (key, vars) => {
    const template = dict[key];
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
      name in vars ? String(vars[name]) : whole
    );
  };
}

export function resolveLang(pref: "auto" | Lang): Lang {
  if (pref !== "auto") return pref;
  const tags = typeof navigator === "undefined" ? [] : navigator.languages;
  return tags.some((tag) => tag.toLowerCase().startsWith("zh")) ? "zh-CN" : "en";
}
